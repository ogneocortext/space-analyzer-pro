"""Agentic tool layer for the live progress dashboard.

This module gives an Ollama model with tool-calling support a safe, scoped
set of tools to *analyze screenshots*, *find issues*, and *make improvements*
without leaving the dashboard:

  * :data:`TOOLS` — the registry (name + description + JSON-schema parameters).
  * :func:`run_tool` — executes a single tool by name and returns a JSON result.
  * :func:`run_agent` — drives a multi-turn tool-calling loop against Ollama's
    ``/api/chat`` endpoint, executing every ``tool_calls`` entry and feeding the
    results back until the model stops requesting tools.

Tools are deliberately read-mostly. The only mutating tools are:

  * ``run_analysis`` / ``run_improvement_loop`` — launch the existing subprocess
    runners (which already refuse a second concurrent run) so the model can kick
    off work it cannot do itself.
  * ``update_issue`` — edit the shared issue tracker (``docs/issues.json``).
  * ``apply_edit`` — apply a *targeted* string replacement to a repo source file.
    It is gated behind an explicit ``auto_apply`` flag from the caller and a
    ``confirm: true`` argument from the model, writes a ``.bak`` backup, and
    appends an audit line to ``macro_logs/agent_edits.jsonl``. Edits outside the
    repository root (e.g. into ``macro_logs``) are rejected.

The module is import-safe: it never starts the HTTP server and only reaches for
Ollama when a tool/agent actually runs, so the dashboard server still boots even
if the Ollama client is unavailable.
"""

