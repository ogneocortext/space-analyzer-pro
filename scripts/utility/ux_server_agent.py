_CLIENT_LOCK = threading.Lock()
_CLIENT: OllamaClient | None = None


def _client() -> OllamaClient:
    global _CLIENT
    with _CLIENT_LOCK:
        if _CLIENT is None:
            _CLIENT = OllamaClient(timeout=_CLIENT_TIMEOUT_S)
    return _CLIENT


def list_ollama_models() -> list[str]:
    """Return installed Ollama model names (best-effort)."""
    try:
        models = _client().list_models()
    except Exception:
        return []
    out: list[str] = []
    for m in models:
        if isinstance(m, dict) and m.get("name"):
            out.append(str(m["name"]))
    return out


def _model_supports_tools(name: str) -> bool:
    """Heuristic: does this model family do Ollama native tool calling?"""
    n = (name or "").lower()
    if "embed" in n:
        return False
    for k in (
        "qwen3", "qwen2.5", "qwen2", "llama3", "llama-3", "deepseek", "mistral",
        "mixtral", "gemma2", "gemma3", "gemma4", "qwq", "phi4", "phi-4",
        "command-r", "nemotron", "codellama", "llama3.1", "llama3.2", "llama3.3",
    ):
        if k in n:
            return True
    return False


def _model_is_vision(name: str) -> bool:
    """Heuristic: can this model accept image input?"""
    n = (name or "").lower()
    for k in (
        "vl", "vision", "llava", "moondream", "minicpm-v", "minicpmv", "cogvlm",
        "glm-4v", "internvl", "qwen-vl", "gemma4",
    ):
        if k in n:
            return True
    return False


# Preferred models for the agent's main tool-calling chat, in order. The first
# installed one wins; this keeps the "Default" model button useful without the
# user having to know which coding models are pulled.
_CHAT_MODEL_PREFS = [
    "qwen3:8b", "qwen3:4b", "qwen3:latest", "qwen3", "qwen3-vl:4b",
    "qwen3-vl:2b", "deepseek-r1:7b", "llama3.2:3b",
]
# Vision models for read_screenshot / analyzer runs, most-capable first.
_VISION_MODEL_PREFS = [
    "qwen3-vl:4b", "qwen3-vl:2b", "gemma4:e2b-it-qat", "llama3.2-vision",
]


def select_chat_model(requested: str | None = None) -> str:
    """Pick a model for the agent's tool-calling loop.

    If the caller named a model we honor it (even if not currently installed —
    Ollama will surface a clear "not found" error rather than silently swapping).
    Otherwise we route to the best *installed* tool-capable model, falling back
    to any installed model, then a sane hardcoded default.
    """
    if requested and requested.strip():
        return requested.strip()
    models = list_ollama_models()
    installed = set(models)
    for p in _CHAT_MODEL_PREFS:
        if p in installed:
            return p
    tool_models = [m for m in models if _model_supports_tools(m)]
    if tool_models:
        return tool_models[0]
    if models:
        return models[0]
    return "qwen3:latest"


def select_vision_model(requested: str | None = None) -> str:
    """Pick a vision model for screenshot description / analysis runs."""
    if requested and requested.strip():
        return requested.strip()
    models = list_ollama_models()
    installed = set(models)
    for p in _VISION_MODEL_PREFS:
        if p in installed:
            return p
    vision = [m for m in models if _model_is_vision(m)]
    if vision:
        return vision[0]
    # Known-good vision default even if not yet pulled (Ollama will fetch/error).
    return "gemma4:e2b-it-qat"


def _resolve_repo_file(repo_root: Path, path: str) -> Path | None:
    """Resolve a repo-relative path, ensuring it stays inside the repo root."""
    try:
        p = (repo_root / path)
        if p.is_absolute():
            p = p
        p = p.resolve()
        p.relative_to(repo_root.resolve())
    except (OSError, ValueError):
        return None
    return p


