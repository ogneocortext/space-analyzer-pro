def _coerce_tool_args(raw: Any) -> dict:
    if isinstance(raw, dict):
        return raw
    if isinstance(raw, str):
        try:
            parsed = json.loads(raw)
            if isinstance(parsed, dict):
                return parsed
        except (json.JSONDecodeError, ValueError):
            pass
    return {}


def _extract_assistant_text(msg: Any) -> str:
    """Pull the assistant's user-visible text out of an Ollama ``message``.

    Some models (notably qwen3-vl) stream their reasoning into a ``thinking``
    field even when ``think=False``, leaving ``content`` empty. If ``content``
    is blank we fall back to the cleaned ``thinking`` text so the agent loop
    and the user still get a usable answer. A leading ``<think>…</think>``
    block (occasionally embedded in ``content``) is stripped either way.
    """
    if not isinstance(msg, dict):
        return ""
    text = msg.get("content") or ""
    if not text:
        th = msg.get("thinking") or ""
        if th:
            text = re.sub(r"</?think>", "", th, flags=re.I).strip()
    if "<think>" in text:
        text = re.sub(r"<think>.*?</think>", "", text, flags=re.S | re.I).strip()
    return text


def run_agent(user_message: str, model: str, ctx: dict, *,
              history: list[dict] | None = None,
              max_iterations: int = 6, auto_apply: bool = False) -> dict:
    """Run a tool-calling agent loop against Ollama and return the transcript.

    Returns ``{"answer", "transcript", "iterations", "model", "error?"}``.
    ``transcript`` is a list of steps: assistant turns (with optional tool_calls)
    and tool-result turns (name/args/result) for the UI to render.
    """
    tools_schema = list_tool_schemas()
    client = _client()
    # Route the chat model: an explicit, non-empty model is honored as-is; an
    # empty one ("Default") is sent to the best installed tool-capable model.
    model = select_chat_model(model)
    messages: list[dict[str, Any]] = [{"role": "system", "content": AGENT_SYSTEM}]
    for h in (history or []):
        if isinstance(h, dict) and h.get("role") in ("user", "assistant"):
            messages.append({
                "role": h["role"],
                "content": str(h.get("content", "")),
            })
    messages.append({"role": "user", "content": user_message})

    transcript: list[dict[str, Any]] = []
    last_answer = ""
    iterations = 0
    try:
        for i in range(max(1, int(max_iterations))):
            iterations = i + 1
            msg = client.chat_with_tools(
                model, messages, tools_schema, think=False,
                options={"num_ctx": 8192},
            )
            content = _extract_assistant_text(msg)
            tool_calls = msg.get("tool_calls") or []
            assistant_step: dict[str, Any] = {
                "role": "assistant",
                "content": content,
                "tool_calls": tool_calls,
            }
            messages.append({
                "role": "assistant",
                "content": content,
                **({"tool_calls": tool_calls} if tool_calls else {}),
            })
            transcript.append(assistant_step)
            if not tool_calls:
                last_answer = content
                break
            for tc in tool_calls:
                fn = tc.get("function", {}) if isinstance(tc, dict) else {}
                name = fn.get("name", "")
                args = _coerce_tool_args(fn.get("arguments"))
                result = run_tool(name, args, ctx, auto_apply=auto_apply)
                transcript.append({
                    "role": "tool",
                    "name": name,
                    "args": args,
                    "result": result,
                })
                messages.append({
                    "role": "tool",
                    "content": json.dumps(result, ensure_ascii=False, default=str),
                    "name": name,
                })
            last_answer = content
    except Exception as exc:
        return {
            "answer": last_answer,
            "transcript": transcript,
            "iterations": iterations,
            "model": model,
            "error": f"{type(exc).__name__}: {exc}",
        }
    return {
        "answer": last_answer,
        "transcript": transcript,
        "iterations": iterations,
        "model": model,
    }
