def _tool_read_screenshot(args: dict, ctx: dict) -> dict:
    root_base: Path = ctx["root_base"]
    set_rel = (args.get("set") or "").strip()
    filename = (args.get("filename") or "").strip()
    if not set_rel or not filename:
        return {"ok": False, "error": "set and filename are required"}
    safe_name = Path(filename).name
    base = _safe_path(root_base, set_rel)
    if base is None or not base.is_dir():
        return {"ok": False, "error": f"unknown capture set: {set_rel}"}
    img = base / safe_name
    if not img.is_file():
        # fall back to a recursive search so the caller need not know subfolders
        hits = sorted(base.rglob(safe_name))
        if not hits:
            return {"ok": False, "error": f"screenshot not found: {safe_name}"}
        img = hits[0]
    try:
        data = img.read_bytes()
    except OSError as exc:
        return {"ok": False, "error": f"cannot read image: {exc}"}
    w = h = None
    try:
        if Image is not None:
            with Image.open(io.BytesIO(data)) as im:
                w, h = im.size
    except Exception:
        pass

    # Surface any stored previews from a live/prior run for this key.
    previews: dict[str, str] = {}
    progress = _read_json(root_base / "analysis_progress.json") or {}
    shots = progress.get("shots") or {}
    key = img.relative_to(root_base).as_posix()
    shot = shots.get(key) or {}
    if isinstance(shot, dict):
        vp = shot.get("vision_preview")
        ap = shot.get("analysis_preview")
        if vp:
            previews["stored_vision_preview"] = vp
        if ap:
            previews["stored_analysis_preview"] = ap

    # Fresh vision description (text) so the model can actually "see" the shot.
    prompt = (args.get("prompt") or "").strip() or (
        "Describe this UI screenshot for a UX review: identify the screen, "
        "visible panels, headings, buttons, inputs, and any obvious layout, "
        "contrast, alignment, or clarity problems."
    )
    vision_model = select_vision_model(ctx.get("vision_model"))
    description = ""
    try:
        description = _client().generate(
            vision_model, prompt, images=[data], think=False, stream=False,
        )
    except Exception as exc:  # vision model may be unavailable; degrade gracefully
        description = f"(vision describe failed: {exc})"
    return {
        "ok": True,
        "path": key,
        "width": w,
        "height": h,
        "size_bytes": len(data),
        "description": description,
        **previews,
    }


def _tool_list_reports(args: dict, ctx: dict) -> dict:
    store = _get_store(ctx["root_base"])
    if store is None:
        return {"ok": False, "status": "unavailable", "error": "reports db missing"}
    try:
        limit = int(args.get("limit") or 20)
    except (TypeError, ValueError):
        limit = 20
    rows = store.list_reports(
        limit=limit, model=args.get("model"), screenshot_set=args.get("set"),
    )
    return {"ok": True, "count": len(rows), "reports": rows}


def _tool_read_report(args: dict, ctx: dict) -> dict:
    store = _get_store(ctx["root_base"])
    if store is None:
        return {"ok": False, "status": "unavailable", "error": "reports db missing"}
    key = (args.get("report_key") or "").strip() or None
    rep = store.get(key) if key else store.get_latest()
    if rep is None:
        return {"ok": False, "error": "no report found"}
    payload = rep.get("report") or {}
    payload["_meta"] = {
        k: rep.get(k)
        for k in ("id", "report_key", "screenshot_set", "model", "status",
                  "timestamp", "num_issues", "num_recommendations", "severity_counts")
    }
    return {"ok": True, "report": payload}


