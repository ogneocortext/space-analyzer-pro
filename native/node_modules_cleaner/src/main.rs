use anyhow::{Context, Result};
use chrono::{DateTime, Utc};
use clap::{Arg, Command};
use rayon::prelude::*;
use serde::{Deserialize, Serialize};
use std::collections::HashMap;
use std::fs;
use std::path::Path;
use std::time::SystemTime;
use walkdir::WalkDir;

#[derive(Debug, Serialize, Deserialize)]
struct CleanupAnalysis {
    total_size: u64,
    total_files: u64,
    total_directories: u64,
    node_modules_count: u64,
    largest_modules: Vec<ModuleInfo>,
    cleanup_candidates: Vec<CleanupCandidate>,
    duplicate_packages: Vec<DuplicatePackage>,
    analysis_time: DateTime<Utc>,
}

#[derive(Debug, Serialize, Deserialize, Clone)]
struct ModuleInfo {
    path: String,
    size: u64,
    file_count: u64,
    directory_count: u64,
    last_modified: Option<DateTime<Utc>>,
    package_name: Option<String>,
    version: Option<String>,
    cleanup_reason: Option<String>,
    risk_level: RiskLevel,
}

#[derive(Debug, Serialize, Deserialize)]
struct CleanupCandidate {
    path: String,
    size: u64,
    reason: String,
    risk_level: RiskLevel,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum RiskLevel {
    Low,
    Medium,
    High,
}

impl RiskLevel {
    fn as_str(&self) -> &'static str {
        match self {
            RiskLevel::Low => "Low",
            RiskLevel::Medium => "Medium",
            RiskLevel::High => "High",
        }
    }
}

impl Serialize for RiskLevel {
    fn serialize<S>(&self, serializer: S) -> Result<S::Ok, S::Error>
    where
        S: serde::Serializer,
    {
        serializer.serialize_str(self.as_str())
    }
}

impl<'de> Deserialize<'de> for RiskLevel {
    fn deserialize<D>(deserializer: D) -> Result<Self, D::Error>
    where
        D: serde::Deserializer<'de>,
    {
        let s = String::deserialize(deserializer)?;
        match s.as_str() {
            "Low" => Ok(RiskLevel::Low),
            "Medium" => Ok(RiskLevel::Medium),
            "High" => Ok(RiskLevel::High),
            _ => Err(serde::de::Error::unknown_variant(
                &s,
                &["Low", "Medium", "High"],
            )),
        }
    }
}

#[derive(Debug, Serialize, Deserialize)]
struct DuplicatePackage {
    name: String,
    versions: Vec<String>,
    total_size: u64,
    locations: Vec<String>,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum CleanupMode {
    DryRun,
    Actual,
}

fn main() -> Result<()> {
    let matches = Command::new("node_modules_cleaner")
        .version("1.0.0")
        .about("High-performance node_modules cleanup and analysis tool")
        .arg(
            Arg::new("path")
                .help("Directory path to analyze")
                .required(true)
                .index(1),
        )
        .arg(
            Arg::new("output")
                .short('o')
                .long("output")
                .value_name("FILE")
                .help("Output results to a JSON file"),
        )
        .arg(
            Arg::new("cleanup")
                .long("cleanup")
                .help("Actually perform cleanup operations (destructive)")
                .action(clap::ArgAction::SetTrue),
        )
        .arg(
            Arg::new("min-size")
                .long("min-size")
                .value_name("MB")
                .help("Minimum size in MB to consider for cleanup")
                .default_value("100"),
        )
        .arg(
            Arg::new("unused-days")
                .long("unused-days")
                .value_name("DAYS")
                .help("Consider modules unused for this many days")
                .default_value("30"),
        )
        .arg(
            Arg::new("parallel")
                .long("parallel")
                .help("Use parallel processing for faster analysis")
                .action(clap::ArgAction::SetTrue),
        )
        .arg(
            Arg::new("progress")
                .long("progress")
                .help("Show progress output")
                .action(clap::ArgAction::SetTrue),
        )
        .get_matches();

    let path = Path::new(matches.get_one::<String>("path").unwrap());
    let output_file = matches.get_one::<String>("output");
    let cleanup_mode = if matches.get_flag("cleanup") {
        CleanupMode::Actual
    } else {
        CleanupMode::DryRun
    };
    let min_size_mb: u64 = matches
        .get_one::<String>("min-size")
        .unwrap()
        .parse()
        .context("Invalid min-size value")?;
    let unused_days: u64 = matches
        .get_one::<String>("unused-days")
        .unwrap()
        .parse()
        .context("Invalid unused-days value")?;
    let parallel = matches.get_flag("parallel");
    let show_progress = matches.get_flag("progress");

    if !path.exists() {
        anyhow::bail!("Path does not exist: {}", path.display());
    }
    if !path.is_dir() {
        anyhow::bail!("Path is not a directory: {}", path.display());
    }

    if cleanup_mode == CleanupMode::Actual {
        eprintln!("⚠️  CLEANUP MODE — files will be permanently deleted!");
        eprintln!("   Target: {}", path.display());
    } else {
        println!("🔍 Analyzing node_modules in: {}", path.display());
        println!("📋 Dry run mode — no files will be deleted");
    }

    let analysis = analyze_node_modules(
        path,
        min_size_mb * 1024 * 1024,
        unused_days,
        parallel,
        show_progress,
        cleanup_mode,
    )?;

    println!("\n📊 Analysis Results:");
    println!(
        "Total size analyzed: {} GB",
        format_bytes(analysis.total_size)
    );
    println!("Total files: {}", analysis.total_files);
    println!("Total directories: {}", analysis.total_directories);
    println!("node_modules found: {}", analysis.node_modules_count);

    if !analysis.largest_modules.is_empty() {
        println!("\n🏆 Largest node_modules:");
        for (i, module) in analysis.largest_modules.iter().take(5).enumerate() {
            println!(
                "{}. {} — {} ({} files, {} dirs)",
                i + 1,
                module.path,
                format_bytes(module.size),
                module.file_count,
                module.directory_count
            );
        }
    }

    if !analysis.cleanup_candidates.is_empty() {
        let total_cleanup_size: u64 = analysis.cleanup_candidates.iter().map(|c| c.size).sum();
        println!(
            "\n🧹 Cleanup Candidates ({}):",
            analysis.cleanup_candidates.len()
        );
        println!(
            "Total potential savings: {} GB",
            format_bytes(total_cleanup_size)
        );

        for candidate in &analysis.cleanup_candidates {
            let risk_emoji = match candidate.risk_level {
                RiskLevel::Low => "🟢",
                RiskLevel::Medium => "🟡",
                RiskLevel::High => "🔴",
            };
            println!(
                "{} {} — {} ({})",
                risk_emoji,
                candidate.path,
                format_bytes(candidate.size),
                candidate.reason
            );
        }
    } else {
        println!("\n✅ No cleanup candidates found.");
    }

    if !analysis.duplicate_packages.is_empty() {
        println!(
            "\n📦 Duplicate Packages ({}):",
            analysis.duplicate_packages.len()
        );
        for dup in &analysis.duplicate_packages {
            println!(
                "{} — {} versions: {} — {} GB",
                dup.name,
                dup.versions.len(),
                dup.versions.join(", "),
                format_bytes(dup.total_size)
            );
        }
    }

    if let Some(output_file) = output_file {
        let json_output = serde_json::to_string_pretty(&analysis)?;
        fs::write(output_file, json_output)?;
        println!("\n💾 Results saved to: {}", output_file);
    }

    if cleanup_mode == CleanupMode::DryRun && !analysis.cleanup_candidates.is_empty() {
        println!("\n💡 Run with --cleanup to actually delete the above candidates.");
    }

    Ok(())
}

fn analyze_node_modules(
    root_path: &Path,
    min_size_bytes: u64,
    unused_days: u64,
    parallel: bool,
    show_progress: bool,
    cleanup_mode: CleanupMode,
) -> Result<CleanupAnalysis> {
    let mut node_modules_paths = Vec::new();

    if show_progress {
        println!("🔍 Scanning for node_modules directories...");
    }

    for entry in WalkDir::new(root_path) {
        let entry = entry?;
        let path = entry.path();
        if path.is_dir()
            && path.file_name() == Some(std::ffi::OsStr::new("node_modules"))
            && !is_nested_node_modules(path, root_path)
        {
            node_modules_paths.push(path.to_path_buf());
        }
    }

    if show_progress {
        println!(
            "📁 Found {} node_modules directories",
            node_modules_paths.len()
        );
    }

    let module_infos: Vec<ModuleInfo> = if parallel {
        node_modules_paths
            .par_iter()
            .map(|nm| analyze_module(nm, min_size_bytes, unused_days, show_progress))
            .collect::<Result<Vec<_>>>()?
    } else {
        node_modules_paths
            .iter()
            .map(|nm| analyze_module(nm, min_size_bytes, unused_days, show_progress))
            .collect::<Result<Vec<_>>>()?
    };

    let mut total_size = 0u64;
    let mut total_files = 0u64;
    let mut total_directories = 0u64;
    let mut cleanup_candidates = Vec::new();

    for info in &module_infos {
        total_size += info.size;
        total_files += info.file_count;
        total_directories += info.directory_count;

        if let Some(reason) = &info.cleanup_reason {
            cleanup_candidates.push(CleanupCandidate {
                path: info.path.clone(),
                size: info.size,
                reason: reason.clone(),
                risk_level: info.risk_level,
            });
        }
    }

    if cleanup_mode == CleanupMode::Actual && !cleanup_candidates.is_empty() {
        perform_cleanup(&cleanup_candidates, show_progress)?;
    }

    let mut largest_modules = module_infos.clone();
    largest_modules.sort_by_key(|b| std::cmp::Reverse(b.size));

    let mut package_map: HashMap<String, Vec<&ModuleInfo>> = HashMap::new();
    for info in &module_infos {
        if let Some(name) = &info.package_name {
            package_map.entry(name.clone()).or_default().push(info);
        }
    }

    let mut duplicate_packages = Vec::new();
    for (name, modules) in package_map {
        if modules.len() > 1 {
            let mut versions: Vec<String> = modules
                .iter()
                .filter_map(|m| m.version.clone())
                .collect();
            versions.sort();
            versions.dedup();

            if versions.len() > 1 {
                let total_size: u64 = modules.iter().map(|m| m.size).sum();
                let locations: Vec<String> = modules.iter().map(|m| m.path.clone()).collect();

                duplicate_packages.push(DuplicatePackage {
                    name,
                    versions,
                    total_size,
                    locations,
                });
            }
        }
    }

    let analysis_time = DateTime::<Utc>::from(SystemTime::now());

    Ok(CleanupAnalysis {
        total_size,
        total_files,
        total_directories,
        node_modules_count: node_modules_paths.len() as u64,
        largest_modules,
        cleanup_candidates,
        duplicate_packages,
        analysis_time,
    })
}

fn is_nested_node_modules(path: &Path, root: &Path) -> bool {
    path.strip_prefix(root)
        .map(|rel| rel.components().count() > 1)
        .unwrap_or(false)
}

fn analyze_module(
    path: &Path,
    min_size_bytes: u64,
    unused_days: u64,
    show_progress: bool,
) -> Result<ModuleInfo> {
    if show_progress {
        eprintln!("  analyzing: {}", path.display());
    }

    let mut total_size = 0u64;
    let mut file_count = 0u64;
    let mut directory_count = 0u64;
    let mut last_modified: Option<SystemTime> = None;

    for entry in WalkDir::new(path) {
        let entry = entry?;
        let entry_path = entry.path();

        if entry_path.is_dir() {
            directory_count += 1;
        } else if entry_path.is_file() {
            let metadata = fs::metadata(entry_path)?;
            total_size += metadata.len();
            file_count += 1;

            let modified = metadata.modified()?;
            last_modified = Some(last_modified.map_or(modified, |prev| {
                if modified > prev { modified } else { prev }
            }));
        }
    }

    let (package_name, version) = extract_package_info(path);

    let last_modified_dt = last_modified.map(DateTime::<Utc>::from);

    let now = SystemTime::now();
    let days_old = last_modified
        .and_then(|t| now.duration_since(t).ok())
        .map(|d| d.as_secs() / 86400)
        .unwrap_or(0);

    let cleanup_reason = if total_size > min_size_bytes * 10 {
        Some(format!(
            "Very large ({} GB)",
            total_size / (1024 * 1024 * 1024)
        ))
    } else if days_old > unused_days && total_size > min_size_bytes {
        Some(format!(
            "Unused for {} days, exceeds {} MB",
            days_old,
            min_size_bytes / (1024 * 1024)
        ))
    } else {
        None
    };

    let risk_level = assess_risk(days_old, package_name.as_deref());

    Ok(ModuleInfo {
        path: path.to_string_lossy().to_string(),
        size: total_size,
        file_count,
        directory_count,
        last_modified: last_modified_dt,
        package_name,
        version,
        cleanup_reason,
        risk_level,
    })
}

fn extract_package_info(node_modules_path: &Path) -> (Option<String>, Option<String>) {
    let mut current = Some(node_modules_path);

    while let Some(dir) = current {
        if let Some(parent) = dir.parent() {
            let package_json_path = parent.join("package.json");
            if package_json_path.exists() {
                if let Ok(content) = fs::read_to_string(&package_json_path) {
                    if let Ok(package_data) = serde_json::from_str::<serde_json::Value>(&content) {
                        let name = package_data
                            .get("name")
                            .and_then(|v| v.as_str())
                            .map(|s| s.to_string());
                        let version = package_data
                            .get("version")
                            .and_then(|v| v.as_str())
                            .map(|s| s.to_string());
                        return (name, version);
                    }
                }
            }
        }
        current = dir.parent();
    }

    (None, None)
}

fn assess_risk(days_old: u64, package_name: Option<&str>) -> RiskLevel {
    if days_old < 7 {
        return RiskLevel::High;
    }

    if let Some(name) = package_name {
        let lower = name.to_lowercase();
        if lower.contains("dev") || lower.contains("test") || lower.contains("@types") {
            return RiskLevel::Medium;
        }
    }

    if days_old > 365 {
        return RiskLevel::High;
    } else if days_old > 90 {
        return RiskLevel::Medium;
    }

    RiskLevel::Low
}

fn perform_cleanup(candidates: &[CleanupCandidate], show_progress: bool) -> Result<()> {
    if show_progress {
        println!("\n🗑️  Deleting {} candidates...", candidates.len());
    }

    let mut deleted = 0u64;
    let mut failed = 0u64;

    for candidate in candidates {
        let path = Path::new(&candidate.path);
        if !path.exists() {
            if show_progress {
                eprintln!("  SKIP (missing): {}", candidate.path);
            }
            continue;
        }

        match fs::remove_dir_all(path) {
            Ok(_) => {
                deleted += 1;
                if show_progress {
                    println!("  DELETED: {}", candidate.path);
                }
            }
            Err(e) => {
                failed += 1;
                eprintln!("  FAILED: {} — {}", candidate.path, e);
            }
        }
    }

    println!("\n✅ Cleanup complete: {} deleted, {} failed", deleted, failed);

    if failed > 0 {
        anyhow::bail!("{} deletions failed", failed);
    }

    Ok(())
}

fn format_bytes(bytes: u64) -> String {
    const UNITS: &[&str] = &["B", "KB", "MB", "GB", "TB"];
    let mut size = bytes as f64;
    let mut unit_index = 0;

    while size >= 1024.0 && unit_index < UNITS.len() - 1 {
        size /= 1024.0;
        unit_index += 1;
    }

    if unit_index == 0 {
        format!("{} {}", bytes, UNITS[unit_index])
    } else {
        format!("{:.2} {}", size, UNITS[unit_index])
    }
}
